def alias_list(software: dict | object) -> list[str]:
    raw = software["aliases"] if isinstance(software, dict) else (software.aliases or "")
    items = [software["name"] if isinstance(software, dict) else software.name, software["slug"] if isinstance(software, dict) else software.slug]
    items.extend(a.strip() for a in raw.split(",") if a.strip())
    return [a.lower() for a in items]


