def heuristic_parse(query: str) -> dict | None:
    import re

    cleaned = query.strip()
    cleaned = re.sub(
        r"^(我想装|帮我装|请帮我安装|给我装|安装|download|install)\s*",
        "",
        cleaned,
        flags=re.I,
    ).strip(" 。.!！")
    if not cleaned:
        return None
    key = re.sub(r"[\s_-]+", "", cleaned.lower())
    if key in SEARCH_HINTS:
        return dict(SEARCH_HINTS[key])
    slug = re.sub(r"[^a-z0-9]+", "-", cleaned.lower()).strip("-")
    if len(slug) < 2:
        return None
    source = "pypi" if re.search(r"lang|torch|numpy|pandas|django|flask", slug) else "npm"
    return {
        "name": cleaned,
        "slug": slug,
        "kind": "library",
        "version_source": source,
        "source_key": slug,
        "winget_id": "",
        "official_url": "",
        "use_official_link": False,
        "platforms": "windows,macos,linux",
    }
